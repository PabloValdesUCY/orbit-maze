"""Record a live demonstration and verify the predictions emitted by the board."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
import re
from statistics import median

import serial

from capture import GESTURES, ROOT, parse_data, read_status, record_gesture
from motion_data import LABELS, MAX_GAP_MS, WINDOW_SIZE


def read_predictions(path):
    """Match every reported prediction to its sample window in the serial log."""
    samples = 0
    previous = None
    pending = None
    predictions = []
    with path.open(encoding='utf-8') as log:
        for line in log:
            line = line.strip()
            if line.startswith('RESULT,'):
                fields = line.split(',')
                if len(fields) != 3:
                    raise ValueError('RESULT is missing a class ID or board timestamp.')
                class_id, end_ms = map(int, fields[1:])
                if pending is None or end_ms != pending[1] or not 0 <= class_id < len(LABELS):
                    raise ValueError('Invalid RESULT or timestamp outside the expected window.')
                predictions.append({
                    'class': LABELS[class_id], 'end_ms': end_ms, 'span_ms': end_ms - pending[0],
                })
                pending = None
                continue
            row = parse_data(line)
            if row is not None:
                if pending is not None:
                    raise ValueError('A sample arrived before the expected RESULT for the previous window.')
                timestamp = row[0]
                if previous is not None and timestamp <= previous:
                    raise ValueError('Timestamps are not strictly increasing in the demo log.')
                if previous is not None and timestamp - previous > MAX_GAP_MS:
                    samples = 0
                if samples == 0:
                    start_ms = timestamp
                samples += 1
                if samples == WINDOW_SIZE:
                    pending = (start_ms, timestamp)
                    samples = 0
                previous = timestamp
    # Recording may end between the last DATA frame and its RESULT.
    if not predictions:
        raise ValueError('The board emitted no valid predictions during the gesture.')
    return predictions, pending is not None


def load_run(run_id):
    run_dir = ROOT / 'results' / run_id
    manifest = json.loads((run_dir / 'manifest.json').read_text(encoding='utf-8'))
    digest = hashlib.sha256((run_dir / 'Model.h').read_bytes()).hexdigest()
    if manifest['run_id_utc'] != run_id or manifest['model']['sha256'] != digest:
        raise ValueError('The manifest and Model.h do not match the requested training run.')
    return digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--port', required=True, help='Serial port verified with capture.py --list')
    parser.add_argument('--run', required=True, help='Name of the results folder for the model on the board')
    args = parser.parse_args()
    if not re.fullmatch(r'[0-9]{8}T[0-9]{12}Z', args.run):
        parser.error('--run must be the UTC training ID generated by training.py')
    digest = load_run(args.run)
    with serial.Serial(args.port, 115200, timeout=0.1, write_timeout=2) as port:
        device = read_status(port)
        if device['model_run_id'] != args.run:
            raise RuntimeError(f"The board reports {device['model_run_id']}. Upload the firmware for {args.run}.")
        if not device['pmu_ready'] or not device['imu_ready']:
            raise RuntimeError('Power management or the IMU failed to initialize.')
        if not device['oled_initialized']:
            print('The OLED did not initialize. Check the display separately.')
        name = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
        directory = ROOT / 'data' / 'demo' / name
        directory.mkdir(parents=True, exist_ok=False)
        evidence = {
            'demo_id_utc': name, 'status': 'incomplete', 'device': device, 'model_sha256': digest,
            'port': args.port, 'gestures': {},
        }
        evidence_path = directory / 'demo.json'

        def save():
            evidence_path.write_text(json.dumps(evidence, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

        save()
        try:
            print(f'Demo logs: {directory}')
            for label, instruction in GESTURES.items():
                print('\n' + instruction)
                input('Press Enter, then perform the gesture during recording and watch the OLED. ')
                recording = record_gesture(port, directory, label, 12)
                predictions, tail = read_predictions(directory / f'{label}.log')
                counts = {item: sum(row['class'] == item for row in predictions) for item in LABELS}
                print(f'Correct predictions for {label}: {counts[label]}/{len(predictions)}')
                evidence['gestures'][label] = {
                    **recording, 'prediction_counts': counts, 'predictions': predictions,
                    'median_window_span_ms': median(row['span_ms'] for row in predictions),
                    'unconfirmed_tail_window': tail,
                }
                save()
                observed = input('Was a label visible on the OLED? [y/n or Enter if you did not check] ')
                evidence['gestures'][label]['oled_text_visible'] = {
                    'y': True, 'yes': True, 'n': False, 'no': False,
                }.get(observed.strip().casefold())
                save()
            if read_status(port) != device:
                raise RuntimeError('The board status changed during the demonstration.')
            evidence['notes'] = input('Note what the OLED showed, any issues and any photo or video filenames: ')
            evidence['status'] = 'complete'
        finally:
            save()
    print('Demo recorded. See demo.json and attach any photos or video of the OLED.')


if __name__ == '__main__':
    try:
        main()
    except (OSError, KeyError, ValueError, RuntimeError, KeyboardInterrupt, EOFError) as error:
        raise SystemExit(f'Demo stopped: {error} Previously saved logs have been kept.')
